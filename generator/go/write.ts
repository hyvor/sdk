import { spawnSync } from 'child_process';

export const GO_MODULE = 'github.com/hyvor/sdk/go';
export const CORE_IMPORT = `${GO_MODULE}/core`;

export interface GoGeneratedFile {
    relativePath: string;
    content: string;
}

export const GENERATED_MARKER = '// Code generated by hyvor/sdk generator';

/**
 * Tracks a Go file's package clause and imports so generation code can
 * request a package by import path and get back the identifier to write.
 * Only ever imports whole packages (stdlib + core), whose names are fixed, so
 * no aliasing is needed.
 */
export class GoFile {
    private imports = new Set<string>();

    constructor(
        private readonly packageName: string,
        private readonly product: string,
    ) {
    }

    use(importPath: string): string {
        this.imports.add(importPath);
        return importPath.split('/').pop()!;
    }

    private renderImports(): string {
        if (this.imports.size === 0) return '';

        const all = Array.from(this.imports).sort();
        const std = all.filter(path => !path.includes('.'));
        const third = all.filter(path => path.includes('.'));
        const groups = [std, third].filter(group => group.length > 0)
            .map(group => group.map(path => `\t"${path}"`).join('\n'));

        return `import (\n${groups.join('\n\n')}\n)\n\n`;
    }

    /**
     * `bodyHasPackageClause`: the body starts with its own package doc
     * comment + `package` clause (so the doc comment attaches to it), and
     * only the imports are spliced in after it.
     */
    render(body: string, bodyHasPackageClause = false): string {
        const header = `${GENERATED_MARKER} from openapi/${this.product}.json; DO NOT EDIT.\n\n`;

        if (bodyHasPackageClause) {
            const marker = `\npackage ${this.packageName}\n`;
            const at = body.indexOf(marker) + marker.length;
            return formatGo(`${header}${body.slice(0, at)}\n${this.renderImports()}${body.slice(at).replace(/^\n+/, '')}\n`);
        }

        return formatGo(`${header}package ${this.packageName}\n\n${this.renderImports()}${body}\n`);
    }
}

let warnedMissingGofmt = false;

/**
 * Runs the code through `gofmt` (field alignment, spacing), so generated
 * files are always gofmt-clean. Falls back to the unformatted code, with a
 * warning, if no `gofmt` binary is available. A gofmt failure means the
 * generator produced invalid Go, and is reported as an error.
 */
export function formatGo(code: string): string {
    const result = spawnSync('gofmt', [], { input: code, encoding: 'utf-8' });

    if (result.error && (result.error as NodeJS.ErrnoException).code === 'ENOENT') {
        if (!warnedMissingGofmt) {
            console.warn('warning: gofmt not found in PATH - Go output is not formatted.');
            warnedMissingGofmt = true;
        }
        return code;
    }

    if (result.status !== 0) {
        throw new Error(`gofmt failed on generated code:\n${result.stderr}\n--- code ---\n${code}`);
    }

    return result.stdout;
}
